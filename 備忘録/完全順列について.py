"""
完全順列とは
1からnの順列pであって 任意のiで p[i] != i であるもの

完全順列の総数をモンモール数という。しばしば !n と書かれる。

p[n]に置く数の選び方: (n-1) 通り
p[p[n]] == n なら: a[n-2] 通り  [x, x, 5, x, 3] size=3 の完全順列
p[p[n]] != n なら: a[n-1] 通り  [x, 5, x, x, 3] 5 を 3 とみなすと size=4 の完全順列

a[1] = 0
a[2] = 1
a[n] = (n-1) * (a[n-1] + a[n-2])
"""

n = 10

f = [0] * (n + 1)
f[2] = 1
for i in range(3, n + 1):
    f[i] = (i - 1) * (f[i - 1] + f[i - 2])

print(f)
